#!/usr/bin/env python3
"""Pack indexed battle and treasure scenery into RGB565 firmware data."""
from pathlib import Path

from PIL import Image

from pack_home_art import emit_array

TOOLS = Path(__file__).resolve().parent
BIOMES = ("meadow", "beach", "woodland", "volcano", "mountain", "snow")


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def moonlit(r, g, b):
    # Lift the blues and retain detail in the darkest areas.
    return rgb565(7 + r * 45 // 100, 11 + g * 52 // 100, 24 + b * 65 // 100)


def pack_scene(label, filename, size, night=False):
    with Image.open(TOOLS / "activity_art" / filename) as source:
        if source.mode != "P" or source.size != size or not source.getpalette():
            raise SystemExit(f"{filename} must be an indexed PNG at {size}")
        channels = source.getpalette()
        pixels = list(source.get_flattened_data())
    colors = list(zip(channels[::3], channels[1::3], channels[2::3]))
    palette = [rgb565(*color) for color in colors]
    if len(palette) > 256 or max(pixels) >= len(palette):
        raise SystemExit(f"{filename} has an invalid palette")
    arrays = [
        emit_array(f"{label}_PALETTE", palette, 8, ("uint16_t", lambda v: f"0x{v:04X}")),
        emit_array(f"{label}_PIXELS", pixels, 32, ("uint8_t", str)),
    ]
    if night:
        arrays.append(emit_array(f"{label}_NIGHT_PALETTE", [moonlit(*color) for color in colors],
                                 8, ("uint16_t", lambda v: f"0x{v:04X}")))
    return arrays


def main():
    sections = [
        "// Generated by tools/pack_scene_art.py.",
        "#pragma once\n#include <Arduino.h>",
        "static constexpr int ARENA_W = 233, ARENA_H = 127;",
        "static constexpr int CAVERN_W = 185, CAVERN_H = 121;",
        *pack_scene("CAVERN", "treasure-cavern.png", (185, 121)),
    ]
    for name in BIOMES:
        sections.extend(pack_scene(name.upper(), f"{name}-arena.png", (233, 127), night=True))
    entries = [
        f"  {{ {name}_PIXELS, {{ {name}_PALETTE, {name}_NIGHT_PALETTE }} }},"
        for name in map(str.upper, BIOMES)
    ]
    sections.append("\n".join([
        "struct BattleBackdrop { const uint8_t *pixels; const uint16_t *palettes[2]; };",
        "static const BattleBackdrop BATTLE_BACKDROPS[] = {",
        *entries,
        "};",
    ]))
    (TOOLS.parent / "scene_backs.h").write_text("\n\n".join(sections) + "\n")


if __name__ == "__main__":
    main()
