#!/usr/bin/env python3
"""Convert the indexed woodland and cavern plates into RGB565 firmware data."""
from pathlib import Path

from PIL import Image

from pack_home_art import emit_array

TOOLS = Path(__file__).resolve().parent


def pack_scene(label, filename, size):
    with Image.open(TOOLS / "activity_art" / filename) as source:
        if source.mode != "P" or source.size != size or not source.getpalette():
            raise SystemExit(f"{filename} must be an indexed PNG at {size}")
        channels = source.getpalette()
        pixels = list(source.get_flattened_data())
    palette = [
        ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        for r, g, b in zip(channels[::3], channels[1::3], channels[2::3])
    ]
    if len(palette) > 256 or max(pixels) >= len(palette):
        raise SystemExit(f"{filename} has an invalid palette")
    return [
        f"static constexpr int {label}_W = {size[0]}, {label}_H = {size[1]};",
        emit_array(f"{label}_PALETTE", palette, 8, ("uint16_t", lambda v: f"0x{v:04X}")),
        emit_array(f"{label}_PIXELS", pixels, 32, ("uint8_t", str)),
    ]


def main():
    sections = [
        "// Generated by tools/pack_scene_art.py.",
        "#pragma once\n#include <Arduino.h>",
        *pack_scene("WOODLAND", "woodland-arena.png", (233, 127)),
        *pack_scene("CAVERN", "treasure-cavern.png", (185, 121)),
    ]
    (TOOLS.parent / "scene_backs.h").write_text("\n\n".join(sections) + "\n")


if __name__ == "__main__":
    main()
