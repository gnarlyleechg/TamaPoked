#!/usr/bin/env python3
"""Pack the approved TamaPup day/night room art as RGB565 indexed firmware data."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
ART = ROOT / "home_art"
OUT = ROOT.parent / "home_backs.h"
EXPECTED = (233, 156)


def emit_array(name, values, width, formatter):
    lines = [f"static const {formatter[0]} {name}[{len(values)}] PROGMEM = {{"]
    for start in range(0, len(values), width):
        lines.append("  " + ", ".join(formatter[1](v) for v in values[start:start + width]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    sections = [
        "// Generated by tools/pack_home_art.py from tools/home_art/day.png and night.png.",
        "// Palette-indexed 233x156 art; each source pixel is drawn as a 2x2 block.",
        "#pragma once",
        "#include <Arduino.h>",
        "#define ROOM_ART_W 233",
        "#define ROOM_ART_H 156",
    ]
    for label in ("day", "night"):
        image = Image.open(ART / f"{label}.png").convert("RGB")
        if image.size != EXPECTED:
            raise SystemExit(f"{label}.png must be {EXPECTED[0]}x{EXPECTED[1]}, got {image.size}")
        pixels = list(image.get_flattened_data())
        colors = list(dict.fromkeys(pixels))
        if len(colors) > 256:
            raise SystemExit(f"{label}.png has {len(colors)} colors; maximum is 256")
        lookup = {color: index for index, color in enumerate(colors)}
        palette = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in colors]
        indices = [lookup[color] for color in pixels]
        sections.extend([
            emit_array(f"ROOM_{label.upper()}_PALETTE", palette, 8,
                       ("uint16_t", lambda v: f"0x{v:04X}")),
            emit_array(f"ROOM_{label.upper()}_PIXELS", indices, 24,
                       ("uint8_t", lambda v: f"{v}")),
        ])
    OUT.write_text("\n\n".join(sections) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
