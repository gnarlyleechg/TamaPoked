#!/usr/bin/env python3
"""Pack the indexed Prien Lake background for the ESP32 display."""
from pathlib import Path

from PIL import Image

from pack_home_art import emit_array

TOOLS = Path(__file__).resolve().parent
SOURCE = TOOLS / "activity_art" / "prien-lake.png"
OUTPUT = TOOLS.parent / "fishing_back.h"
SIZE = (193, 125)


def main():
    with Image.open(SOURCE) as source:
        if source.mode != "P" or source.size != SIZE:
            raise SystemExit("Prien Lake art must be a 193x125 indexed PNG.")
        channels = source.getpalette()
        pixels = list(source.get_flattened_data())
    palette = [
        ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        for r, g, b in zip(channels[::3], channels[1::3], channels[2::3])
    ]
    sections = [
        "// Generated by tools/pack_fishing_art.py.",
        "#pragma once\n#include <Arduino.h>",
        f"static constexpr int FISH_ART_W = {SIZE[0]}, FISH_ART_H = {SIZE[1]};",
        emit_array("FISH_ART_PALETTE", palette, 8, ("uint16_t", lambda v: f"0x{v:04X}")),
        emit_array("FISH_ART_PIXELS", pixels, 24, ("uint8_t", str)),
    ]
    OUTPUT.write_text("\n\n".join(sections) + "\n")


if __name__ == "__main__":
    main()
